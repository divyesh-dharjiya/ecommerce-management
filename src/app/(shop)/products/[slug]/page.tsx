import type { Metadata } from "next";
import { SEED_CATEGORIES } from "@/data";
import { SEED_PRODUCTS_FULL, getProductDetails } from "@/data/server";
import { siteConfig } from "@/config/site";
import { buildMetadata, productSchema, truncate } from "@/lib/seo";
import { JsonLd } from "@/components/seo/json-ld";
import { ProductDetail } from "@/features/catalog/components/product-detail";

type Props = { params: Promise<{ slug: string }> };

const findSeed = (slug: string) => SEED_PRODUCTS_FULL.find((p) => p.slug === slug);

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { slug } = await params;
  const product = findSeed(slug);
  if (!product) return buildMetadata({ title: "Product", path: `/products/${slug}`, noIndex: true });
  return buildMetadata({
    title: `${product.title} by ${product.brand}`,
    description: truncate(
      `${product.description} Free shipping over $100 · ${product.returnPolicy ?? "Easy returns"}.`,
    ),
    path: `/products/${slug}`,
    keywords: [product.brand, product.category.replace(/-/g, " "), ...product.tags],
    // The Open Graph image is generated by ./opengraph-image.tsx.
    other: {
      "product:price:amount": product.price.toFixed(2),
      "product:price:currency": siteConfig.currency,
      "product:availability": product.stock > 0 ? "in stock" : "out of stock",
      "product:brand": product.brand,
    },
  });
}

/** Pre-render the seed catalogue; admin-created products render on demand. */
export function generateStaticParams() {
  return SEED_PRODUCTS_FULL.map((p) => ({ slug: p.slug }));
}

export default async function ProductPage({ params }: Props) {
  const { slug } = await params;
  const seed = findSeed(slug);
  return (
    <>
      {seed && (
        <JsonLd
          data={productSchema(
            seed,
            SEED_CATEGORIES.find((c) => c.slug === seed.category),
          )}
        />
      )}
      {/* Only this product's heavy details are serialized for the client, not the whole catalog. */}
      <ProductDetail slug={slug} details={seed ? getProductDetails(seed.id) : undefined} />
    </>
  );
}
